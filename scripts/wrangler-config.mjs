// Writes apps/<app>/wrangler.deploy.jsonc: the app's wrangler.jsonc with ${VAR} placeholders filled
// from the environment (or the repo's gitignored .env). Account-specific values, such as the KV
// namespace ids and staging URLs, stay out of the public configs this way.
//
//   node scripts/wrangler-config.mjs <staging|production> [app ...]
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

export const ROOT = fileURLToPath(new URL('..', import.meta.url));
export const TARGETS = ['staging', 'production'];
export const APPS = readdirSync(join(ROOT, 'apps')).filter((app) =>
  existsSync(join(ROOT, 'apps', app, 'wrangler.jsonc')),
);

/** Loads KEY=value lines from the repo's .env without overriding the real environment. */
export function loadDotEnv() {
  const file = join(ROOT, '.env');
  if (!existsSync(file)) return;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
    if (m && process.env[m[1]] === undefined) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
  }
}

const PLACEHOLDER = /\$\{([A-Z0-9_]+)\}/g;

function fill(value, missing) {
  if (typeof value === 'string') {
    return value.replace(PLACEHOLDER, (whole, name) => {
      const v = process.env[name];
      if (!v) {
        missing.add(name);
        return whole;
      }
      return v;
    });
  }
  if (Array.isArray(value)) return value.map((v) => fill(v, missing));
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, fill(v, missing)]));
  }
  return value;
}

/** Fills one app's config for a target and returns the generated file's path. */
export function writeDeployConfig(app, target) {
  const src = join(ROOT, 'apps', app, 'wrangler.jsonc');
  const { config, error } = ts.parseConfigFileTextToJson(src, readFileSync(src, 'utf8'));
  if (error) throw new Error(`${src}: ${ts.flattenDiagnosticMessageText(error.messageText, '\n')}`);

  // Only the section being deployed must be complete; the other one may keep its placeholders.
  const { env = {}, ...top } = config;
  const missing = new Set();
  fill(target === 'production' ? top : (env[target] ?? {}), missing);
  if (missing.size > 0) {
    throw new Error(
      `apps/${app}: set ${[...missing].join(', ')} in the environment or .env to deploy ${target}`,
    );
  }

  const dest = join(ROOT, 'apps', app, 'wrangler.deploy.jsonc');
  const out = fill(config, new Set());
  writeFileSync(
    dest,
    `// Generated by scripts/wrangler-config.mjs. Do not edit or commit.\n${JSON.stringify(out, null, 2)}\n`,
  );
  return dest;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [target, ...apps] = process.argv.slice(2);
  if (!TARGETS.includes(target)) {
    console.error('usage: node scripts/wrangler-config.mjs <staging|production> [app ...]');
    process.exit(2);
  }
  loadDotEnv();
  for (const app of apps.length > 0 ? apps : APPS) console.log(writeDeployConfig(app, target));
}
